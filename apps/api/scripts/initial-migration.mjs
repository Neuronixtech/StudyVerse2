#!/usr/bin/env node
// Builds prisma/migrations/20261125070533_init/migration.sql from the repository:
//   Part 1  `prisma migrate diff --from-empty --to-schema prisma/schema.prisma --script`
//           (the pinned Prisma CLI; no database needed), without its
//           CREATE SCHEMA IF NOT EXISTS "public" preamble
//   Part 2  prisma/extra-constraints.sql, verbatim
// wrapped in BEGIN/COMMIT, because Prisma doesn't make migrations transactional.
//
//   npm run db:initial-migration           rewrite the file
//   npm run db:initial-migration -- --check  exit 1 if the committed file differs
//
// Only for the initial migration, and only until it has been applied anywhere shared.
// After that it is frozen, and schema changes go in new migrations.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const API_ROOT = fileURLToPath(new URL("..", import.meta.url));
const PRISMA_DIR = fileURLToPath(new URL("../../../prisma/", import.meta.url));
const NAME = "20261125070533_init";
const TARGET = `${PRISMA_DIR}migrations/${NAME}/migration.sql`;
const PREAMBLE = '-- CreateSchema\nCREATE SCHEMA IF NOT EXISTS "public";\n\n';

const generated = execFileSync(
  `${API_ROOT}node_modules/.bin/prisma`,
  ["migrate", "diff", "--from-empty", "--to-schema", "../../prisma/schema.prisma", "--script"],
  { cwd: API_ROOT, encoding: "utf8", env: { ...process.env, DATABASE_MIGRATION_URL: "" } },
);
if (!generated.startsWith(PREAMBLE)) {
  throw new Error("Unexpected prisma migrate diff output: the CREATE SCHEMA preamble is missing.");
}
const part1 = generated.slice(PREAMBLE.length).replace(/\n+$/, "");
const part2 = readFileSync(`${PRISMA_DIR}extra-constraints.sql`, "utf8").replace(/\n+$/, "");

const migration = `-- StudyVerse initial migration.
--
-- Part 1 is generated by Prisma 7.10.1 from prisma/schema.prisma
-- (\`prisma migrate dev --create-only --name init\`, identical to
-- \`prisma migrate diff --from-empty --to-schema prisma/schema.prisma --script\`).
-- Part 2 is prisma/extra-constraints.sql, appended verbatim.
--
-- Wrapped in one transaction, because Prisma 7.10.1 doesn't guarantee one. On
-- PostgreSQL 18.7 it sent a script without dollar-quoted bodies one statement at
-- a time, each committed on its own, and a script with them (like this one) as a
-- single message. With BEGIN/COMMIT, a failure rolls back every statement either
-- way. Prisma then reports "current transaction is aborted" instead of the cause,
-- which is in the PostgreSQL log, and records the attempt as failed. To recover,
-- run \`prisma migrate resolve --rolled-back ${NAME}\`, then deploy again.

BEGIN;

-- =============================================================================
-- Part 1: generated by Prisma
-- =============================================================================

${part1}

-- =============================================================================
-- Part 2: prisma/extra-constraints.sql (verbatim)
-- =============================================================================

${part2}

COMMIT;
`;

if (process.argv.includes("--check")) {
  const committed = readFileSync(TARGET, "utf8");
  if (committed !== migration) {
    console.error(
      `${NAME}/migration.sql differs from what the schema and extra-constraints.sql produce.`,
    );
    console.error("Run `npm run db:initial-migration` and review the diff.");
    process.exit(1);
  }
  console.log(`${NAME}/migration.sql is reproducible from the repository.`);
} else {
  writeFileSync(TARGET, migration);
  console.log(`Wrote ${NAME}/migration.sql (${migration.split("\n").length - 1} lines).`);
}
