/** Copies questions with test-scoped ids so the same bank item can appear in several tests */
function section(testKey: string, id: string, name: string, questions: Question[], durationMin = 0, subjectId?: TestSection["subjectId"]): TestSection {
  return {
    id: `${testKey}-${id}`,
    name,
    subjectId,
    durationMin,
    questions: questions.map((q) => ({
      ...q,
      id: `${testKey}-${q.id}`,
      options: q.options.map((o) => ({ ...o, id: `${testKey}-${o.id}` })),
      correctOptionIds: q.correctOptionIds.map((o) => `${testKey}-${o}`),
    })),
  };
}

