import type { Question, SubjectId } from "../types";

type Difficulty = Question["difficulty"];

function opts(id: string, texts: string[]) {
  return texts.map((text, i) => ({ id: `${id}-${String.fromCharCode(97 + i)}`, text }));
}

function single(
  id: string,
  subjectId: SubjectId,
  text: string,
  options: string[],
  correct: number,
  explanation: string,
  difficulty: Difficulty = "Medium",
): Question {
  const o = opts(id, options);
  return { id, type: "single", subjectId, text, options: o, correctOptionIds: [o[correct].id], explanation, difficulty };
}

function multi(
  id: string,
  subjectId: SubjectId,
  text: string,
  options: string[],
  correct: number[],
  explanation: string,
  difficulty: Difficulty = "Medium",
): Question {
  const o = opts(id, options);
  return {
    id,
    type: "multi",
    subjectId,
    text,
    options: o,
    correctOptionIds: correct.map((i) => o[i].id),
    explanation,
    difficulty,
  };
}

function numerical(
  id: string,
  subjectId: SubjectId,
  text: string,
  value: number,
  explanation: string,
  { tolerance = 0, precision = 0, allowNegative = false, difficulty = "Medium" as Difficulty } = {},
): Question {
  return {
    id,
    type: "numerical",
    subjectId,
    text,
    options: [],
    correctOptionIds: [],
    numerical: { value, tolerance, precision, allowNegative },
    explanation,
    difficulty,
  };
}

